package main

import (
	"fmt"

	"github.com/code-by-meal/go-rdp/log"
	serverdata "github.com/code-by-meal/go-rdp/stack/rdp/server_data"
	"github.com/code-by-meal/go-rdp/stack/sec"
)

// Income params for session keys (testing)
var (
	ClientRandom  = []byte{0xB2, 0x16, 0x0A, 0xFC, 0x14, 0xB2, 0xAE, 0x18, 0xCE, 0x67, 0x15, 0x2D, 0x4A, 0xD2, 0x1F, 0x0F, 0xAB, 0x16, 0x32, 0x3F, 0x17, 0xEB, 0xAA, 0x2E, 0x58, 0x6F, 0xCE, 0x2C, 0xE9, 0x86, 0x1F, 0x2F}
	ServerRandom  = []byte{0xAA, 0xF5, 0xB2, 0x1B, 0x04, 0xDC, 0xA4, 0xF0, 0x6A, 0xA4, 0x5F, 0x06, 0x46, 0x9D, 0x85, 0xAD, 0xDC, 0x9A, 0x1E, 0x79, 0x2B, 0x6D, 0x64, 0xFF, 0xA0, 0x54, 0xA2, 0xF8, 0x83, 0xB9, 0x19, 0xFB}
	EncryptMethod = serverdata.One28BIT
)

func main() {
	sk := sec.NewSessionKey(EncryptMethod)

	log.Dbg("<s>Client Random:</>", ClientRandom)
	log.Dbg("<s>Server Random:</>", ServerRandom)

	if err := sk.Calc(ClientRandom, ServerRandom); err != nil {
		fmt.Println("Error calculate session keys: ", err)

		return
	}
}
